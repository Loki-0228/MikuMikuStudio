HOST = Path("MikuMikuDance.exe")
PROVIDER = Path("PLUGINS/legacy-mmdplugin/MMDPlugin.dll")
TEMPLATE = Path("mms-adaptive-ui-template.zip")
CTEST_CASES = ("legacy_mmd_menu_commands", "legacy_observer_export_preflight", "abi_release_package_layout")
MANUAL_CASES = ("observer-and-aa", "product-still-png", "product-sequence-29-31", "product-transparent-mov")
PROBES = (
    ("still-native-shell-component", "image_sequence_tests.exe", "--still-shell-only", "PASS native still export Shell"),
    ("still-render-component", "image_sequence_tests.exe", "--still-only", "PASS automatic still-image checks="),
    ("mov-publication-component", "native_media_tests.exe", "--mov-publication", "PASS WIC MOV publication"),
)


def require(ok, message):
    if not ok:
        raise ValueError(message)


def digest(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def require_file(path):
    require(path.is_file() and not path.is_symlink(), f"Expected a regular file: {path}")
    return path


def require_pe_x64(path):
    """Preflight rejects text fixtures and wrong-architecture inputs without loading them."""
    with require_file(path).open("rb") as stream:
        head = stream.read(64)
        require(len(head) == 64 and head[:2] == b"MZ", f"No DOS/PE header: {path}")
        stream.seek(struct.unpack_from("<I", head, 60)[0])
        pe = stream.read(26)
        require(len(pe) == 26 and pe[:6] == b"PE\0\0\x64\x86" and pe[24:26] == b"\x0b\x02",
                f"Not a PE32+ x64 binary: {path}")
    return path


def cache_values(build, repo):
    cache = require_file(build / "CMakeCache.txt").read_text(encoding="utf-8-sig")
    keys = ("CMAKE_HOME_DIRECTORY", "CMAKE_GENERATOR", "CMAKE_GENERATOR_PLATFORM", "CMAKE_INSTALL_PREFIX",
            "MIKUMIKUSTUDIO_PROFILE", "MIKUMIKUSTUDIO_BUILD_UI_TESTS", "MIKUMIKUSTUDIO_WIN7_BASELINE",
            "MIKUMIKUSTUDIO_DEPLOYMENT_INSTALL", "MIKUMIKUSTUDIO_ENABLE_DX12")
    values = {key: re.search(rf"(?m)^{key}:[^=\r\n]+=(.*)$", cache) for key in keys}
    values = {key: match[1].strip() if match else None for key, match in values.items()}
    source = values["CMAKE_HOME_DIRECTORY"]
    require(source and Path(source).resolve() == repo, "Build CMakeCache.txt is for a different checkout")
    require(values["CMAKE_GENERATOR_PLATFORM"] == "x64" and values["MIKUMIKUSTUDIO_PROFILE"] == "full",
            "Build must be the complete x64 profile")
    require(values["MIKUMIKUSTUDIO_BUILD_UI_TESTS"] in {"1", "ON", "TRUE", "YES"}, "Enable MIKUMIKUSTUDIO_BUILD_UI_TESTS")
    return values


def git(repo, *args):
    return subprocess.check_output(["git", "-C", str(repo), *args])


def snapshot_source(repo, build):
    paths = git(repo, "ls-files", "-z", "--cached", "--others", "--exclude-standard").split(b"\0")
    hashes = {}
    for name in sorted(set(paths) - {b""}):
        relative = Path(os.fsdecode(name))
        path = repo / relative
        if path.is_relative_to(build) or relative.is_relative_to(Path("build/packages")):
            continue
        require(not path.is_symlink(), f"Cannot snapshot a symbolic-link source input: {path}")
        require(path.is_file() or not path.exists(), f"Unexpected non-file source input: {path}")
        hashes[relative.as_posix()] = digest(path) if path.is_file() else None
    return {"head": git(repo, "rev-parse", "HEAD").decode().strip(), "files_sha256": hashes}


def verify_template(path, source):
    with zipfile.ZipFile(path) as archive:
        entries = archive.infolist()
        require(entries and sum(item.file_size for item in entries) < 32 * 1024 * 1024,
                "Expected a small adaptive UI source archive")
        names = {item.filename for item in entries}
        manifests = [name for name in names if name.count("/") == 1 and name.endswith("/MANIFEST.json")]
        require(len(names) == len(entries) and len(manifests) == 1, "Invalid adaptive UI archive inventory")
        manifest = json.loads(archive.read(manifests[0]))
        require(manifest.get("schemaVersion") == 1 and manifest.get("name") == "mms-adaptive-ui-template"
                and manifest.get("binariesIncluded") is False and manifest.get("sourceCommit") == source["head"],
                "Adaptive UI template manifest must identify this checkout's HEAD and a source-only package")
        require(manifest.get("packagerSha256") == source["files_sha256"].get("tools/package-adaptive-ui-template.py"),
                "Adaptive UI template was generated by a different packager")
        prefix = manifests[0].split("/", 1)[0] + "/"
        hashes = manifest["files"]
        require(isinstance(hashes, dict) and {"LICENSE", "CMakeLists.txt", "README.md"}.issubset(hashes),
                "Invalid adaptive UI manifest files")
        require(names == {prefix + name for name in hashes} | set(manifests), "Unexpected archive entries")
        originals = {name: value for name, value in source["files_sha256"].items()
                     if name == "LICENSE" or name.startswith("third_party/native_ui/")}
        require({name: hashes.get(name) for name in originals} == originals, "Adaptive UI archived source hashes differ")
        for name, expected in hashes.items():
            require(all(part not in {"", ".", ".."} for part in name.split("/")) and "\\" not in name,
                    f"Invalid adaptive UI archive entry: {name}")
            require(hashlib.sha256(archive.read(prefix + name)).hexdigest() == expected,
                    f"Adaptive UI archive member SHA-256 differs: {name}")


def verify_package(release, installed, build_binaries, archive, source_licenses, source_config):
    expected = {HOST.name, "MMDFacade.dll", "MMHack.dll", "PLUGINS", "optional-plugins",
                "LICENSE", TEMPLATE.name, "licenses"}
    require({item.name for item in release.iterdir()} == expected, "Unexpected top-level release contents")
    require({item.name for item in (release / PROVIDER.parent).iterdir()} == {PROVIDER.name},
            "Private provider directory contains files other than MMDPlugin.dll")
    for path in (release, installed):
        providers = [item.relative_to(path) for item in path.rglob("*") if item.name.casefold() == PROVIDER.name.casefold()]
        require(providers == [PROVIDER], f"Expected a single private MMDPlugin.dll in {path}: {providers}")
    hashes = {}
    pairs = [(name, build_binaries / name, (release / name, installed / name)) for name in (HOST, PROVIDER)]
    pairs.extend([
        (TEMPLATE, archive, (release / TEMPLATE,)),
        (Path("PLUGINS/config.json"), source_config, (installed / "PLUGINS/config.json",)),
    ])
    licenses = {path.relative_to(source_licenses) for path in source_licenses.rglob("*") if path.is_file()}
    require(licenses, "The checkout's licenses directory is empty")
    for path in (release, installed):
        packaged = {item.relative_to(path / "licenses") for item in (path / "licenses").rglob("*") if item.is_file()}
        require(packaged == licenses, f"Unexpected license inventory in {path}")
    pairs.extend((Path("licenses") / name, source_licenses / name,
                  (release / "licenses" / name, installed / "licenses" / name)) for name in sorted(licenses))
    for name, source, copies in pairs:
        expected_hash = digest(require_file(source))
        for copy in copies:
            require(digest(require_file(copy)) == expected_hash, f"SHA-256 differs from the input: {copy}")
        hashes[name.as_posix()] = {"source": str(source), "copies": [str(path) for path in copies], "sha256": expected_hash}
    return hashes


class Evidence:
    def __init__(self, root):
        self.root = root
        self.results = {}
        self.flush()

    def write(self, name, value):
        (self.root / name).write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    def flush(self):
        self.write("summary.json", {"automated": self.results,
                                    "manual": dict.fromkeys(MANUAL_CASES, "NOT RUN"),
                                    "deployment_closure": "NOT VERIFIED"})

    def record(self, case, status, detail):
        self.results[case] = {"status": status, "detail": detail}
        self.flush()
        print(f"{status} {case}: {detail}", flush=True)

    def command(self, case, command, cwd, timeout, *, env=None, marker=None, no_tests=False):
        command = list(map(str, command))
        path = self.root / f"{case}.log"
        with path.open("wb") as log:
            log.write((json.dumps({"command": command, "cwd": str(cwd), "timeout_seconds": timeout}, ensure_ascii=False) + "\n").encode("utf-8"))
            log.flush()
            try:
                completed = subprocess.run(command, cwd=cwd, env=env, timeout=timeout, check=False,
                                           stdout=log, stderr=subprocess.STDOUT,
                                           creationflags=subprocess.CREATE_NO_WINDOW)
            except subprocess.TimeoutExpired:
                self.record(case, "FAIL", f"timed out; {path.name}")
                return False
            except OSError as error:
                self.record(case, "BLOCKED", f"{error}; {path.name}")
                return False
        ok = completed.returncode == 0
        if ok and marker is not None:
            ok = marker.encode() in path.read_bytes()
        detail = f"exit {completed.returncode}; {path.name}"
        if completed.returncode == 0 and not ok:
            detail += f"; missing expected result {marker!r}"
        if no_tests and b"No tests were found" in path.read_bytes():
            self.record(case, "BLOCKED", f"CTest case was not registered; {path.name}")
            return False
        self.record(case, "PASS" if ok else "FAIL", detail)
        return ok


def run(args, evidence):
    build = args.build.resolve()
    repo = Path(__file__).resolve().parents[1]
    archive = args.ui_template.absolute()
    release, installed = (evidence.root / name for name in ("release", "cmake-install"))
    build_binaries = build / "Release"
    try:
        require(shutil.which("git"), "Git is not available on PATH")
        require_file(archive)
        cache = cache_values(build, repo)
        probes = build / "tests/Release"
        inputs = [require_pe_x64(build_binaries / name) for name in (HOST, PROVIDER)]
        inputs.extend([build / "CMakeCache.txt", archive])
        probe_errors = {}
        for name in sorted({probe[1] for probe in PROBES}):
            try:
                inputs.append(require_pe_x64(probes / name))
            except (OSError, ValueError) as error:
                probe_errors[name] = str(error)
        before = snapshot_source(repo, build)
        binaries = {str(path): digest(path) for path in inputs}
        evidence.write("source-before.json", before)
        evidence.write("build.json", {"source": str(repo), "build": str(build), "cache": cache,
                                      "sha256": binaries, "windows": list(sys.getwindowsversion()),
                                      "python": sys.version})
        verify_template(archive, before)
        evidence.record("preflight", "PASS", "full x64 UI-test build, template manifest and input hashes; build.json")
    except (KeyError, OSError, ValueError, zipfile.BadZipFile, subprocess.SubprocessError) as error:
        evidence.record("preflight", "BLOCKED", str(error))
        return 1

    def external(case, tool, *arguments, timeout=180, no_tests=False):
        executable = shutil.which(tool)
        if not executable:
            evidence.record(case, "BLOCKED", f"{tool} is not available on PATH")
            return False
        return evidence.command(case, (executable, *arguments), evidence.root, timeout, no_tests=no_tests)

    packed = external("release-packager", "pwsh", "-NoProfile", "-NonInteractive", "-File",
                      repo / "scripts/package_abi_release.ps1", "-BuildDirectory", build,
                      "-ReleaseDirectory", release, "-UiTemplateArchive", archive)
    staged = external("cmake-install", "cmake", "--install", build, "--config", "Release", "--prefix", installed)
    if packed and staged:
        try:
            hashes = verify_package(release, installed, build_binaries, archive, repo / "licenses", repo / "PLUGINS/config.json")
            evidence.write("package-hashes.json", hashes)
            evidence.record("package-layout-and-bytes", "PASS", "package-hashes.json")
        except (OSError, ValueError) as error:
            evidence.record("package-layout-and-bytes", "FAIL", str(error))
    else:
        evidence.record("package-layout-and-bytes", "BLOCKED", "release or install staging did not pass")

    for case in CTEST_CASES:
        external(case, "ctest", "--test-dir", build, "-C", "Release", "--output-on-failure",
                 "--no-tests=error", "-R", f"^{case}$", no_tests=True)

    for case, name, mode, marker in PROBES:
        if name in probe_errors:
            evidence.record(case, "BLOCKED", probe_errors[name])
            continue
        try:
            directory = evidence.root / case
            directory.mkdir()
            output = directory / "out"
            output.mkdir()
            for name_ in ("data", "Local", "Roaming", "Temp"):
                (directory / name_).mkdir()
            exe = directory / name
            shutil.copyfile(probes / name, exe)
            require(digest(exe) == binaries[str(probes / name)], f"Test executable copy changed: {exe}")
            env = dict(os.environ, LOCALAPPDATA=str(directory / "Local"), APPDATA=str(directory / "Roaming"),
                       TEMP=str(directory / "Temp"), TMP=str(directory / "Temp"),
                       MIKUMIKUSTUDIO_AUTOSAVE_CONFIG=str(directory / "autosave.ini"),
                       MMS_ANTIALIAS_CONFIG=str(directory / "antialias.ini"),
                       MIKUMIKUSTUDIO_TRACE_FILE=str(directory / "trace.log"))
            argv = (exe, mode, output) if mode == "--mov-publication" else (exe, output, mode)
            evidence.command(case, argv, directory, 180, env=env, marker=marker)
        except (OSError, ValueError) as error:
            evidence.record(case, "BLOCKED", str(error))

    try:
        after = snapshot_source(repo, build)
        evidence.write("source-after.json", after)
        require(before == after, "Git HEAD or source inventory changed; use a quiet checkout and rerun")
        changed = [path for path, expected in binaries.items() if digest(Path(path)) != expected]
        require(not changed, f"Build or template input changed: {changed}")
        evidence.record("inputs-unchanged", "PASS", "source and build/template SHA-256")
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        evidence.record("inputs-unchanged", "FAIL", str(error))
    return int(any(result["status"] != "PASS" for result in evidence.results.values()))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build", type=Path, required=True, help="already-built, disposable full x64 Release tree")
    parser.add_argument("--ui-template", type=Path, required=True, help="existing adaptive UI template ZIP")
    parser.add_argument("--evidence", type=Path, required=True, help="new directory outside checkout and build")
    args = parser.parse_args(argv)
    if os.name != "nt":
        parser.error("Windows only; no package or component commands were executed")
    repo = Path(__file__).resolve().parents[1]
    build = args.build.resolve()
    root = args.evidence.resolve()
    if root.is_relative_to(repo) or root.is_relative_to(build):
        parser.error("--evidence must be outside the source and build trees")
    if build == repo or repo.is_relative_to(build):
        parser.error("--build cannot be the source tree or its ancestor")
    try:
        root.mkdir()
    except OSError as error:
        parser.error(f"--evidence needs an existing parent and a new directory: {error}")
    return run(args, Evidence(root))


if __name__ == "__main__":
    raise SystemExit(main())
