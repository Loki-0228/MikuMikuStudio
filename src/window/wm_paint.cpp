// Buffer only the damaged bounds. The destination remains the BeginPaint DC,
// so its actual update region and WS_CLIPCHILDREN clipping still govern the
// final copy. No modern compositing or graphics-device API is required.
class ChromePaintBuffer {
    HDC target_, memory_ = nullptr;
    HBITMAP bitmap_ = nullptr;
    HGDIOBJ previousBitmap_ = nullptr;
    RECT bounds_;
public:
    ChromePaintBuffer(HDC target, const RECT& bounds) noexcept : target_(target), bounds_(bounds) {
        const int width = bounds.right - bounds.left, height = bounds.bottom - bounds.top;
        if (!target || width <= 0 || height <= 0) return;
        memory_ = CreateCompatibleDC(target);
        if (!memory_) return;
        bitmap_ = CreateCompatibleBitmap(target, width, height);
        if (!bitmap_) return;
        previousBitmap_ = SelectObject(memory_, bitmap_);
        if (!previousBitmap_ || previousBitmap_ == HGDI_ERROR) { previousBitmap_ = nullptr; return; }
        if (!SetViewportOrgEx(memory_, -bounds.left, -bounds.top, nullptr)) return;
        if (IntersectClipRect(memory_, bounds.left, bounds.top, bounds.right, bounds.bottom) == ERROR) return;
        // Preserve gaps that the legacy chrome painter intentionally leaves
        // untouched, rather than copying uninitialized bitmap pixels back.
        if (!BitBlt(memory_, bounds.left, bounds.top, width, height,
                    target, bounds.left, bounds.top, SRCCOPY)) return;
        ready_ = true;
    }
    ~ChromePaintBuffer() {
        if (previousBitmap_) SelectObject(memory_, previousBitmap_);
        if (bitmap_) DeleteObject(bitmap_);
        if (memory_) DeleteDC(memory_);
    }
    ChromePaintBuffer(const ChromePaintBuffer&) = delete;
    ChromePaintBuffer& operator=(const ChromePaintBuffer&) = delete;
    HDC DrawingDC() const noexcept { return ready_ ? memory_ : target_; }
    bool Present() const noexcept {
        return !ready_ || BitBlt(target_, bounds_.left, bounds_.top,
            bounds_.right - bounds_.left, bounds_.bottom - bounds_.top,
            memory_, bounds_.left, bounds_.top, SRCCOPY) != FALSE;
    }
private:
    bool ready_ = false;
};

